// - 쓰는 때: 엔진 intent.resolve가 판정 불가(decide.unavailable)일 때만. 온라인은 모델 판정(adviceMentioned·refuse_advice)만 쓴다.
// - 하는 일: 걸리면 고정 문구(ADVICE_TEXT)만 덧붙인다. 작업(초안·안내)을 바꾸거나 거부하지 않는다.
// - 공제·절세·경비 인정·세액 판단을 묻는 말만 넣는다. 급여 계산 요청("이번 달 원천세 얼마야")과 발급·증명서 요청(부가세 별도·포함, 납세증명서,
//   공제증명서)은 걸리지 않아야 한다(tests/shell-advice-words.test.ts가 두 쪽 문장을 모두 본다).
// - 띄어쓰기를 지운 문장에 맞춘다(구어 띄어쓰기 차이).

/** 세무 상담으로 보는 말(띄어쓰기 없앤 문장에 맞춘다). */
export const OFFLINE_ADVICE_PATTERNS: readonly RegExp[] = [
  /절세/,
  /(세금|세액|부가세|종소세|종합소득세|법인세|소득세)(을|를|이|가|좀)?(줄이|줄일|줄여|아끼|아낄|덜내|덜낼)/,
  /(경비|비용)(으로|로)?(처리|인정)(돼|되|할수|가능|해도|하면|받)/,
  /(경비|비용)(으로|로)?(넣어도|넣으면|넣을수|잡아도|잡으면)/,
  /공제(받|되|돼|가능|대상|할수)/,
  /(세금|부가세|종소세|종합소득세|법인세|소득세)(을|를|은|는|이|가)?(얼마나?|몇)(내|나와|나올|낼|돌려)/,
  /(환급|감면)(받|되|돼|가능)/,
  /가산세(안|피하|피할|줄)/,
  /(신고|세금)(를|을)?(안|안하|빼먹)(으면|하면|해도|내면)/,
  /(세무|세금)(상담|조언)/,
];

/** 오프라인에서 세무 상담이 섞인 문장인가(고정 문구만 덧붙일지). */
export function offlineAdviceMentioned(text: string): boolean {
  const t = text.replace(/\s+/g, '');
  return OFFLINE_ADVICE_PATTERNS.some((p) => p.test(t));
}
